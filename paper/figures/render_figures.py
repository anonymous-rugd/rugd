"""Render the 5 data-driven figures as vector PDFs with matplotlib, reading the exact same
CSVs as the (now-retired) PGFPlots sources in this directory.

Why: Overleaf's free-tier compile timeout was hit repeatedly on this paper. The dominant cost
is not the LaTeX text -- it's that cleveref/hyperref/xr-hyper/natbib require 3-4 full
recompiles to resolve all cross-references and citations, and every one of those passes was
re-executing 6 separate TikZ/PGFPlots figures from source. Pre-rendering the 5 purely
data-driven figures (everything except the architecture diagram, which stays hand-drawn TikZ
per the original figure-source requirement) to already-built vector PDFs removes that cost
almost entirely: LaTeX then just places a finished PDF via \\includegraphics, which is cheap
on every pass.

Run from the repository root: python paper/figures/render_figures.py
Every number plotted here comes from paper/figures/data/*.csv, which is itself generated by
paper/figures/regenerate_figure_data.py from the retained study CSVs -- nothing here is
invented, and the visual content matches the retired PGFPlots sources
(figures/*_pgfplots_source.tex, kept for reference / a future non-time-constrained compile).
"""
from pathlib import Path

import matplotlib
matplotlib.use("pdf")
import matplotlib.pyplot as plt
import matplotlib.ticker as mticker
import pandas as pd

plt.rcParams.update({
    "font.size": 9, "axes.titlesize": 9.5, "axes.labelsize": 9,
    "xtick.labelsize": 8, "ytick.labelsize": 8, "legend.fontsize": 7.5,
    "pdf.fonttype": 42, "ps.fonttype": 42,  # embed as real vector text, not paths
})

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"


def save(fig, name, tight=True):
    if tight:
        fig.tight_layout()
    fig.savefig(ROOT / f"{name}.pdf", bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {name}.pdf")


def main_severe_auprc():
    df = pd.read_csv(DATA / "main_severe_auprc.csv").sort_values("mean")
    fig, ax = plt.subplots(figsize=(6.3, 4.2))
    colors = ["#2f5f8a" if lbl != "ShiftGuard-RUGD" else "#1a3a5c" for lbl in df["label"]]
    ax.barh(df["label"], df["mean"], xerr=df["sd"], color=colors, alpha=0.85,
            error_kw={"ecolor": "black", "elinewidth": 0.8, "capsize": 2})
    for y, (m, lbl) in enumerate(zip(df["mean"], df["label"])):
        ax.text(m + 0.03, y, f"{m:.3f}", va="center", fontsize=7)
    ax.set_xlabel("Severe-congestion AUPRC (mean $\\pm$ SD, 9 city--seed runs)")
    ax.set_xlim(0, 1.05)
    ax.set_title("Leave-one-city-out performance")
    save(fig, "main_severe_auprc")


def ablation_waterfall():
    df = pd.read_csv(DATA / "ablation_delta.csv").sort_values("delta")
    fig, ax = plt.subplots(figsize=(6.3, 3.2))
    colors = ["#8c2f2f" if d == df["delta"].min() else "#c47a4a" for d in df["delta"]]
    ax.barh(df["label"], df["delta"], color=colors, alpha=0.9)
    for y, d in enumerate(df["delta"]):
        ax.text(d - 0.0006 if d < 0 else d + 0.0002, y, f"{d:+.4f}",
                va="center", ha="right" if d < 0 else "left", fontsize=7)
    ax.set_xlabel("Clean severe AUPRC $\\Delta$ vs. full ShiftGuard-RUGD")
    ax.axvline(0, color="black", linewidth=0.6)
    save(fig, "ablation_waterfall")


def robustness():
    focus = ["rugd", "staeformer_inductive", "graph_gru", "gru", "opencity_scratch", "uignn_inductive"]
    name_map = {"rugd": "ShiftGuard-RUGD", "staeformer_inductive": "STAEformer",
                "graph_gru": "Graph-GRU", "gru": "GRU", "opencity_scratch": "OpenCity-Scratch",
                "uignn_inductive": "UIGNN"}
    colors = {"rugd": "#1a3a5c", "staeformer_inductive": "#8c2f2f", "graph_gru": "#2f8c6a",
              "gru": "#c47a4a", "opencity_scratch": "#7a4a9c", "uignn_inductive": "#666666"}
    markers = {"rugd": "o", "staeformer_inductive": "^", "graph_gru": "s",
               "gru": "D", "opencity_scratch": "p", "uignn_inductive": "x"}
    fig, axes = plt.subplots(1, 3, figsize=(9.5, 3.2))
    titles = {"missing": ("Missing rate", "Missingness"), "noise": ("Noise $\\sigma$", "Gaussian noise"),
              "shift": ("Temporal shift (bins)", "Temporal shift")}
    for ax, cond in zip(axes, ["missing", "noise", "shift"]):
        for m in focus:
            d = pd.read_csv(DATA / f"robustness_{cond}_{m}.csv")
            ax.plot(d["severity"], d["severe_auprc"], marker=markers[m], color=colors[m],
                    label=name_map[m], linewidth=1.2, markersize=4)
        ax.set_xlabel(titles[cond][0])
        ax.set_title(titles[cond][1])
        if cond == "missing":
            ax.set_ylabel("Severe AUPRC")
    axes[0].legend(loc="upper center", bbox_to_anchor=(1.7, 1.32), ncol=6, frameon=False,
                   columnspacing=1.0, handletextpad=0.4)
    save(fig, "robustness")


def confusion_matrix():
    # Drawn as explicit Rectangle patches + a manually built colorbar, not imshow(): imshow
    # rasterizes its cell data into an embedded bitmap even in a PDF backend, which this
    # project's figures otherwise avoid entirely (verified with pdfimages -list; every other
    # figure here has zero embedded raster images).
    import matplotlib.patches as patches

    df = pd.read_csv(DATA / "confusion_matrix_grid.csv")
    labels = ["normal", "warning", "severe"]
    grid = df.pivot(index="y", columns="x", values="value").to_numpy()
    cmap = matplotlib.colormaps["Blues"]
    fig, ax = plt.subplots(figsize=(4.0, 3.6))
    for y in range(3):
        for x in range(3):
            v = grid[y, x]
            ax.add_patch(patches.Rectangle((x - 0.5, y - 0.5), 1, 1, facecolor=cmap(v),
                                            edgecolor="white", linewidth=0.5))
            ax.text(x, y, f"{v:.2f}", ha="center", va="center",
                    color="white" if v > 0.5 else "black", fontsize=8)
    ax.set_xlim(-0.5, 2.5); ax.set_ylim(-0.5, 2.5)
    ax.set_xticks(range(3)); ax.set_xticklabels(labels)
    ax.set_yticks(range(3)); ax.set_yticklabels(labels)
    ax.set_xlabel("Predicted label"); ax.set_ylabel("True label")
    ax.set_aspect("equal")

    # Manual colorbar as stacked Rectangle patches (a built-in fig.colorbar() call rasterizes
    # its gradient even when the underlying data is vector -- confirmed with pdfimages -list).
    cax = fig.add_axes([0.78, 0.15, 0.035, 0.7])
    n_steps = 100
    for i in range(n_steps):
        v0, v1 = i / n_steps, (i + 1) / n_steps
        cax.add_patch(patches.Rectangle((0, v0), 1, v1 - v0, facecolor=cmap((v0 + v1) / 2),
                                         edgecolor="none"))
    cax.set_xlim(0, 1); cax.set_ylim(0, 1)
    cax.set_xticks([])
    cax.yaxis.tick_right()
    cax.set_yticks([0, 0.25, 0.5, 0.75, 1.0])
    fig.subplots_adjust(right=0.75)
    save(fig, "confusion_matrix", tight=False)


def calibration_pr():
    cal = pd.read_csv(DATA / "calibration_curve.csv")
    pr = pd.read_csv(DATA / "pr_curve.csv")
    fig, axes = plt.subplots(1, 2, figsize=(7.4, 3.4))
    axes[0].plot(cal["predicted"], cal["observed"], marker="o", color="#1a3a5c", markersize=3)
    axes[0].plot([0, 1], [0, 1], "--", color="gray", linewidth=0.8)
    axes[0].set_xlabel("Predicted severe probability"); axes[0].set_ylabel("Observed frequency")
    axes[0].set_title("Severe-event calibration")
    axes[0].set_xlim(0, 1); axes[0].set_ylim(0, 1)
    axes[1].plot(pr["recall"], pr["precision"], color="#8c2f2f", linewidth=1.4)
    axes[1].set_xlabel("Recall"); axes[1].set_ylabel("Precision")
    axes[1].set_title("Severe-event PR curve")
    axes[1].set_xlim(0, 1); axes[1].set_ylim(0, 1)
    save(fig, "calibration_pr")


if __name__ == "__main__":
    main_severe_auprc()
    ablation_waterfall()
    robustness()
    confusion_matrix()
    calibration_pr()
